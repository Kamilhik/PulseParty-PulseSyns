import assert from "node:assert/strict";
import { RelayClient, opId, abortableDelay } from "../src/transport.js";
import { actionSchema } from "../shared/protocol.js";
const url = process.argv[2] || "http://127.0.0.1:8788";
const abort = new AbortController();
const action = (value: object) => actionSchema.parse({ ...value, opId: opId() });
const clients = [0, 1, 2].map(() => new RelayClient(url, fetch, abort.signal));
const [a, b, c] = clients;
try {
  const health = await fetch(url + "/v1/health");
  const healthValue = await health.json();
  assert.equal(healthValue.ok, true);
  assert.equal(healthValue.protocol, 1);
  assert.equal(healthValue.build, "0.3.0");
  const origin = "https://addon-1001.pulsesync.invalid";
  const cors = await fetch(url + "/v1/health", { headers: { Origin: origin } });
  assert.equal(cors.headers.get("access-control-allow-origin"), origin);
  const denied = await fetch(url + "/v1/health", { headers: { Origin: "https://evil.invalid" } });
  assert.equal(denied.status, 403);
  assert.equal(denied.headers.get("access-control-allow-origin"), null);
  const page = await fetch(url + "/invite");
  assert.equal(page.status, 200);
  assert.equal(page.headers.get("referrer-policy"), "no-referrer");
  assert.ok(!(await page.text()).includes("pulseparty://"));
  a.session = (await a.call("rooms", { name: "Анна" })).session!;
  const invite = await a.action(action({ type: "invite", profile: false }));
  b.session = (await b.call("join", { name: "Борис", invite: invite.invite })).session!;
  c.session = (await c.call("join", { name: "Вера", invite: invite.invite })).session!;
  const snapshot = (await c.call("snapshot")).snapshot;
  assert.equal(snapshot.members.length, 3);
  const poll = c.call("poll?after=" + snapshot.revision);
  await abortableDelay(100, abort.signal);
  await a.action(action({ type: "ready", epoch: snapshot.epoch, error: null }));
  assert.ok((await poll).snapshot.revision > snapshot.revision);
  await assert.rejects(b.action(action({ type: "skip", direction: "next" })), /owner-only/);
  await assert.rejects(b.action(action({ type: "skipMode", mode: "everyone" })), /owner-only/);
  await a.action(action({ type: "skipMode", mode: "everyone" }));
  const queued = await b.action(action({ type: "skip", direction: "next" }));
  assert.equal(queued.snapshot.skipQueue?.length, 1);
  await a.action(action({ type: "skipDone", id: queued.snapshot.skipQueue![0].id, epoch: snapshot.epoch }));
  await a.action(action({ type: "skipMode", mode: "owner" }));
  const renamed = await b.action(action({ type: "rename", name: "Ник из Яндекс Музыки" }));
  assert.equal(renamed.snapshot.members.find(m => m.id === b.session!.memberId)?.name, "Ник из Яндекс Музыки");
  const playback = { track: { trackId: "123", title: "Песня", artist: "Исполнитель", durationMs: 180000, cover: "" }, playing: true, positionMs: 12000, rate: 1 };
  const published = await a.action(action({ type: "publish", epoch: snapshot.epoch, sequence: 1, playback, sampledAt: a.now() }));
  assert.equal((await b.call("snapshot")).snapshot.playback.track?.trackId, "123");
  await assert.rejects(b.action(action({ type: "close" })), /owner-only/);
  const handoff = action({ type: "handoff", targetId: b.session.memberId });
  const transferred = await a.action(handoff);
  assert.equal((await a.action(handoff)).snapshot.epoch, transferred.snapshot.epoch);
  assert.ok(transferred.snapshot.epoch > published.snapshot.epoch);
  await assert.rejects(a.action(action({ type: "publish", epoch: snapshot.epoch, sequence: 2, playback, sampledAt: a.now() })), /stale-host/);
  await b.action(action({ type: "ready", epoch: transferred.snapshot.epoch, error: null }));
  await b.action(action({ type: "publish", epoch: transferred.snapshot.epoch, sequence: 1, playback: { ...playback, playing: false, positionMs: 5000 }, sampledAt: b.now() }));
  assert.equal((await c.call("snapshot")).snapshot.playback.playing, false);
  await a.action(action({ type: "handoff", targetId: c.session.memberId }));
  await a.action(action({ type: "revokeInvites" }));
  const invalid = await fetch(url + "/v1/invite/check", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ invite: invite.invite }) });
  assert.equal(invalid.status, 410);
  await a.action(action({ type: "close" }));
  await assert.rejects(b.call("snapshot"), /session-expired/);
  const large = await fetch(url + "/v1/rooms", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ name: "x".repeat(17000) }) });
  assert.equal(large.status, 413);
  console.log(`${url.startsWith("https:") ? "Public Cloudflare HTTPS" : "Local Cloudflare workerd"}: 3 clients, HTTP long poll, skip permissions/queue, rename, publications, two handoffs, replay/role checks, revocation, closure, CORS and body limit passed.`);
} finally {
  if (a.session) await a.action(action({ type: "close" })).catch(() => {});
  abort.abort();
}
